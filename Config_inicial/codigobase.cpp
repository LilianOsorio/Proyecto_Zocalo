void DoMovement()
{
	bool moving = false;

	// Velocidades independientes del numero de cuadros
	const float moveSpeed = 3.0f;
	const float turnSpeed = 100.0f;

	float dt = deltaTime;

	// A y D giran al perro
	if (keys[GLFW_KEY_A])
		dogYaw += turnSpeed * dt;

	if (keys[GLFW_KEY_D])
		dogYaw -= turnSpeed * dt;

	// Direccion hacia la que mira el perro.
	// El modelo del perro tiene la cabeza hacia +Z.
	float yawRad = glm::radians(dogYaw);

	glm::vec3 forward(
		sin(yawRad),
		0.0f,
		cos(yawRad)
	);

	// W avanza en la direccion del perro
	if (keys[GLFW_KEY_W])
	{
		dogPos += forward * moveSpeed * dt;
		moving = true;
	}

	// S retrocede
	if (keys[GLFW_KEY_S])
	{
		dogPos -= forward * moveSpeed * dt;
		moving = true;
	}

	// Orientacion usada al dibujar el modelo
	dogRot = dogYaw;

	// Activar o detener la animacion de las patas
	dogAnim = moving ? 1 : 0;

	// Mantener el perro a la altura definida
	dogPos.y = -1.5f;

	// Posicion de la camara: atras y arriba del perro
	glm::vec3 cameraPos =
		dogPos
		- forward * cameraDistance
		+ glm::vec3(0.0f, cameraHeight, 0.0f);

	// Punto al que mira la camara
	glm::vec3 lookTarget =
		dogPos + glm::vec3(0.0f, 0.35f, 0.0f);

	camera.SetPositionAndLookAt(cameraPos, lookTarget);

	// Controles de luz opcionales
	if (keys[GLFW_KEY_T]) pointLightPositions[0].x += 0.01f;
	if (keys[GLFW_KEY_G]) pointLightPositions[0].x -= 0.01f;
	if (keys[GLFW_KEY_Y]) pointLightPositions[0].y += 0.01f;
	if (keys[GLFW_KEY_H]) pointLightPositions[0].y -= 0.01f;
	if (keys[GLFW_KEY_U]) pointLightPositions[0].z -= 0.1f;
	if (keys[GLFW_KEY_J]) pointLightPositions[0].z += 0.01f;
}

void KeyCallback(GLFWwindow* window, int key, int scancode, int action, int mode)
{
	if (GLFW_KEY_ESCAPE == key && GLFW_PRESS == action)
	{
		glfwSetWindowShouldClose(window, GL_TRUE);
	}

	if (key >= 0 && key < 1024)
	{
		if (action == GLFW_PRESS)
		{
			keys[key] = true;
		}
		else if (action == GLFW_RELEASE)
		{
			keys[key] = false;
		}
	}

	if (keys[GLFW_KEY_SPACE])
	{
		active = !active;
		if (active)
		{
			Light1 = glm::vec3(0.2f, 0.8f, 1.0f);
		}
		else
		{
			Light1 = glm::vec3(0);
		}
	}
	if (keys[GLFW_KEY_N])
	{
		AnimBall = !AnimBall;
	}
	if (keys[GLFW_KEY_B])
	{
		dogAnim = 1;
	}
}

void Animation() {
	if (AnimBall)
	{
		rotBall += 0.4f;
	}

	if (AnimDog)
	{
		rotDog -= 0.6f;
	}

	// Estado principal del perro: utiliza tu lógica original de oscilación de patas
	if (dogAnim == 1) // Walk animation 
	{
		if (!step)
		{
			RLegs += 0.5f;
			FLegs += 0.5f;
			head += 0.2f;
			tail += 0.3f;

			if (RLegs > 15.0f)
				step = true;
		}
		else
		{
			RLegs -= 0.5f;
			FLegs -= 0.5f;
			head -= 0.2f;
			tail -= 0.3f;

			if (RLegs < -15.0f)
				step = false;
		}
	}
	else
	{
		// Si te detienes, las patas regresan a su posición inicial
		RLegs = 0.0f;
		FLegs = 0.0f;
		head = 0.0f;
		tail = 0.0f;
	}
}

void MouseCallback(GLFWwindow* window, double xPos, double yPos)
{
	if (firstMouse)
	{
		lastX = xPos;
		lastY = yPos;
		firstMouse = false;
	}

	GLfloat xOffset = xPos - lastX;
	GLfloat yOffset = lastY - yPos;

	lastX = xPos;
	lastY = yPos;

	camera.ProcessMouseMovement(xOffset, yOffset);
}

